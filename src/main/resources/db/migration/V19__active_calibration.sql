-- La taratura attiva di ogni esemplare (PIANO_METROLOGIA 1.11, specifica § 4.1).
--
-- Fino a oggi un sensore si convertiva con la formula del suo modello, cioe' con i
-- coefficienti di targa. Un certificato di taratura dice invece com'e' fatto *quel* sensore:
-- la sua funzione vince sul template finche' e' in vigore.
--
-- Chi scrive qui e' solo il consumer di `calibration-activated`. La fonte e' metrology-service,
-- e il topic e' compattato: svuotando questa tabella, al riavvio lo stato si ricostruisce
-- rileggendo il topic da capo. Non e' quindi un dato di cui fare il backup per se', ma lo
-- storico serve ai campioni che puntano qui, e per quello resta.
--
-- L'esemplare si identifica con la chiave naturale (EUID della MU, indice del sensore), non
-- con l'id della riga `sensor`: una MU che cambia CU, o un sensore ricreato dalla topologia,
-- restano lo stesso strumento fisico, ed e' lo strumento che e' stato tarato.

CREATE TABLE public.active_calibration (
    id                    bigint           NOT NULL,
    -- L'esemplare nello schema metrology, per i rimandi dall'interfaccia.
    calibrated_item_id    bigint,
    mu_extended_id        bigint           NOT NULL,
    sensor_index          integer          NOT NULL,
    -- Il certificato che ha attivato questa funzione, con numero e revisione leggibili.
    certificate_id        bigint           NOT NULL,
    certificate_number    varchar(64),
    revision              integer          NOT NULL DEFAULT 1,
    -- Stessa forma del blocco `calibration` di un template: type, formula, input, c[].
    function              jsonb            NOT NULL,
    -- Matrice di covarianza dei coefficienti, nell'ordine di c[].id.
    covariance            jsonb,
    calibrated_min        double precision,
    calibrated_max        double precision,
    valid_from            timestamptz      NOT NULL,
    valid_until           timestamptz,
    -- Il tombstone del topic: da questo istante la funzione non si usa piu'.
    revoked_at            timestamptz,
    block_a_crc_expected  varchar(8),
    fingerprint           varchar(80),
    received_at           timestamptz      NOT NULL DEFAULT now(),
    CONSTRAINT active_calibration_pkey PRIMARY KEY (id),
    CONSTRAINT active_calibration_unique UNIQUE (mu_extended_id, sensor_index, valid_from)
);

ALTER TABLE public.active_calibration ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.active_calibration_id_seq
    START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

-- La risoluzione di ogni campione: l'esemplare, la piu' recente fra quelle iniziate.
CREATE INDEX idx_active_calibration_item
    ON public.active_calibration (mu_extended_id, sensor_index, valid_from DESC);
