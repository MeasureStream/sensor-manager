-- Gli eventi che sensor-manager deve consegnare a Kafka, scritti nella stessa transazione
-- del dato che li genera (PIANO_METROLOGIA 2.6, specifica § 3).
--
-- Mandare il messaggio dentro la transazione del campione lascia due modi di sbagliare: il
-- messaggio parte e la transazione fallisce (evento di un campione che non esiste), oppure
-- la transazione riesce e Kafka e' giu' (campione senza evento, e la conformita' non lo
-- vedra' mai). Con l'outbox la riga e' parte del dato: se il campione c'e', c'e' anche
-- l'evento da spedire, e un pubblicatore lo consegna quando Kafka risponde.

CREATE TABLE public.outbox_event (
    id           bigint       NOT NULL,
    topic        varchar(64)  NOT NULL,
    event_key    varchar(64),
    payload      jsonb        NOT NULL,
    created_at   timestamptz  NOT NULL DEFAULT now(),
    sent_at      timestamptz,
    attempts     integer      NOT NULL DEFAULT 0,
    last_error   varchar(500),
    CONSTRAINT outbox_event_pkey PRIMARY KEY (id)
);

ALTER TABLE public.outbox_event ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.outbox_event_id_seq
    START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);

-- Il pubblicatore legge solo quelli ancora da spedire, nell'ordine in cui sono nati.
CREATE INDEX idx_outbox_event_pending ON public.outbox_event (id) WHERE sent_at IS NULL;
