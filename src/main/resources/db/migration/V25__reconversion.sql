-- La riconversione: valore registrato e valore corretto (PIANO_METROLOGIA 5.1, specifica § 4.4).
--
-- `value` non si aggiorna mai: e' cio' che il sistema ha detto in quel momento, con la funzione
-- che allora era in vigore. Quando si scopre di piu' — una taratura che vale da prima della
-- sua attivazione, o un as-found fuori tolleranza che rivela una deriva — il valore rivalutato
-- va accanto, in `corrected_value`, con la sua incertezza e la taratura che l'ha prodotto.

ALTER TABLE public.metric_sample
    ADD COLUMN corrected_value          double precision,
    -- Incertezza tipo (k = 1) del valore corretto.
    ADD COLUMN corrected_u              double precision,
    ADD COLUMN corrected_calibration_id bigint,
    ADD COLUMN corrected_at             timestamptz,
    -- La riconversione che ha scritto la correzione: l'ultima vince.
    ADD COLUMN corrected_run_id         bigint,
    ADD CONSTRAINT metric_sample_corrected_calibration_fk
        FOREIGN KEY (corrected_calibration_id) REFERENCES public.active_calibration(id) ON DELETE SET NULL;

-- Ogni riconversione lascia una riga: chi l'ha chiesta, con quale taratura, su quale intervallo,
-- quanti campioni. Si esegue a lotti in background (ReconversionWorker): `cursor_id` e' l'ultimo
-- campione trattato, cosi' un riavvio riprende da dove si era fermata.
--
-- GAP: i campioni fra l'as-found e l'attivazione, riconvertiti con la funzione nuova.
-- DRIFT: i campioni del periodo precedente, con la funzione interpolata fra l'as-left
--        precedente e l'as-found attuale (deriva supposta lineare, correzione/√3 nell'incertezza).
CREATE TABLE public.reconversion_run (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mu_extended_id          bigint        NOT NULL,
    sensor_index            integer       NOT NULL,
    calibration_id          bigint        NOT NULL REFERENCES public.active_calibration(id),
    certificate_id          bigint,
    mode                    varchar(8)    NOT NULL CHECK (mode IN ('GAP', 'DRIFT')),
    from_ts                 timestamptz   NOT NULL,
    to_ts                   timestamptz   NOT NULL,
    requested_by            varchar(64)   NOT NULL,
    reason                  text,
    state                   varchar(16)   NOT NULL DEFAULT 'PENDING' CHECK (state IN ('PENDING', 'RUNNING', 'DONE', 'FAILED')),
    cursor_id               bigint        NOT NULL DEFAULT 0,
    samples                 integer       NOT NULL DEFAULT 0,
    skipped                 integer       NOT NULL DEFAULT 0,
    error                   text,
    created_at              timestamptz   NOT NULL DEFAULT now(),
    started_at              timestamptz,
    finished_at             timestamptz,
    CHECK (to_ts > from_ts)
);
CREATE INDEX idx_reconversion_run_state ON public.reconversion_run (state, id);
-- Un'attivazione riletta dal topic compattato non riprogramma la stessa riconversione.
CREATE UNIQUE INDEX uq_reconversion_run_auto
    ON public.reconversion_run (calibration_id, mode) WHERE requested_by = 'calibration-activated';

-- Le viste di Grafana imparano il valore corretto, in coda come vuole CREATE OR REPLACE VIEW.
CREATE OR REPLACE VIEW grafana.measure_avg_std AS
SELECT m.sensor_id,
       m."timestamp"                                             AS "time",
       MAX(CASE WHEN m.metric = 'mean' THEN m.value END)         AS media,
       CASE
           WHEN MAX(CASE WHEN m.metric = 'variance' THEN m.value END) >= 0
               THEN sqrt(MAX(CASE WHEN m.metric = 'variance' THEN m.value END))
       END                                                       AS deviazione_standard,
       MAX(CASE WHEN m.metric = 'variance' THEN m.value END)     AS varianza,
       2 * MAX(CASE WHEN m.metric = 'mean' THEN m.u_std END)     AS incertezza_estesa,
       MAX(CASE WHEN m.metric = 'mean' THEN m.value END)
           - 2 * MAX(CASE WHEN m.metric = 'mean' THEN m.u_std END) AS banda_inf,
       MAX(CASE WHEN m.metric = 'mean' THEN m.value END)
           + 2 * MAX(CASE WHEN m.metric = 'mean' THEN m.u_std END) AS banda_sup,
       MAX(CASE WHEN m.metric = 'mean' THEN m.quality_flags END) AS flag_qualita,
       bool_or(m.metric = 'mean' AND m.calibration_id IS NOT NULL) AS taratura_esemplare,
       -- Il valore corretto dalla riconversione, se c'e' (fase 5).
       MAX(CASE WHEN m.metric = 'mean' THEN m.corrected_value END) AS media_corretta,
       2 * MAX(CASE WHEN m.metric = 'mean' THEN m.corrected_u END) AS incertezza_estesa_corretta
FROM public.metric_sample m
WHERE m.metric IN ('mean', 'variance')
GROUP BY m.sensor_id, m."timestamp";

CREATE OR REPLACE VIEW grafana.sample_series AS
SELECT mu.extended_id                                 AS mu_extended_id,
       s.sensor_index,
       m.metric,
       COALESCE(m.window_end, m."timestamp")           AS "time",
       m.value,
       m.converted,
       2 * m.u_std                                     AS incertezza_estesa,
       m.value - 2 * m.u_std                           AS banda_inf,
       m.value + 2 * m.u_std                           AS banda_sup,
       m.quality_flags                                 AS flag_qualita,
       m.calibration_id,
       m.corrected_value                               AS valore_corretto,
       m.corrected_value - 2 * m.corrected_u           AS banda_corretta_inf,
       m.corrected_value + 2 * m.corrected_u           AS banda_corretta_sup
FROM public.metric_sample m
JOIN public.sensor s            ON s.id = m.sensor_id
JOIN public.measurement_unit mu ON mu.id = s.mu_id;

